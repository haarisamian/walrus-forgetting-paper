"""
Appendix table: benefit of Phase I simulation pretraining before PIV adaptation.

Paired ablation, identical in every respect except the starting checkpoint:
  arm B (no Phase I) : walrus.pt            -> Phase II PIV
  arm A (+ Phase I)  : walrus.pt -> Phase I -> Phase II PIV
Both use lr=5e-5, batch_size=1, grad_acc=1, max_samples=200, warmup 3 / cooldown 5,
and train on cylinder_real_cl only. Epoch 0 is the zero-shot rollout of each
starting checkpoint, evaluated through the shared phase1_piv_eval_cfg config.
"""
import sys as _s, pathlib as _p; _s.path.insert(0, str(_p.Path(__file__).resolve().parents[1]))
from analysis._paths import ROOT
import glob, io, os, pickle

import torch

torch.storage._load_from_bytes = lambda b: torch.load(
    io.BytesIO(b), map_location="cpu", weights_only=False)

EXP = f"{ROOT}/walrus/experiments"
FER = f"{EXP}/forget_eval_results"
OUT = f"{ROOT}/realpdebench/analysis/plots"

A_RUN = glob.glob(f"{EXP}/walrus_gn_to_gn_real100pct*5e-05")[0]        # + Phase I
B_RUN = glob.glob(f"{EXP}/walrus_pretrained_to_gn_real100pct*5e-05")[0]  # no Phase I
ZERO = {
    "A": f"{FER}/phase1_piv_eval/piv_real/finetune/0/viz/loss_dicts/"
         f"rollout_valid_loss_dict_epoch101_rank0.pkl",
    "B": f"{FER}/pretrained_piv_eval/piv_real/finetune/0/viz/loss_dicts/"
         f"rollout_valid_loss_dict_epoch101_rank0.pkl",
}
KEY = "rollout_valid_realpdebench_cylinder_real_cl/"
EPOCHS = [0, 20, 40, 60, 80, 100]
WINDOWS = ["T=0:1", "T=1:2", "T=2:8", "T=8:22", "T=22:64"]


def load(p):
    with open(p, "rb") as f:
        return pickle.load(f)


def get(arm, ep):
    if ep == 0:
        return load(ZERO[arm])
    run = A_RUN if arm == "A" else B_RUN
    return load(f"{run}/finetune/0/viz/loss_dicts/"
                f"rollout_valid_loss_dict_epoch{ep}_rank0.pkl")


def val(d, metric):
    v = d[KEY + metric]
    return float(v.item() if hasattr(v, "item") else v)


data = {ep: {"A": get("A", ep), "B": get("B", ep)} for ep in EPOCHS}

# every source must expose the same metric set, or the columns are not comparable
ksets = [frozenset(d[a].keys()) for d in data.values() for a in ("A", "B")]
assert len(set(ksets)) == 1, "metric key sets differ across sources"


def fmt(x, lo):
    """Bold the better (lower, or higher for r) of a pair."""
    s = f"{x:.3f}"
    return f"\\textbf{{{s}}}" if lo else s


rows = []
for ep in EPOCHS:
    a, b = data[ep]["A"], data[ep]["B"]
    vA, vB = val(a, "full_VRMSE_T=all_mean"), val(b, "full_VRMSE_T=all_mean")
    nA, nB = val(a, "full_NRMSE_T=all_mean"), val(b, "full_NRMSE_T=all_mean")
    rA, rB = val(a, "full_PearsonR_T=all_mean"), val(b, "full_PearsonR_T=all_mean")
    rows.append((ep, vB, vA, vB / vA, nB, nA, nB / nA, rB, rA))

lines = [
    r"% Generated by tab_appendix_pretrain_benefit.py -- do not edit by hand.",
    r"\begin{table}[t]",
    r"\centering",
    r"\caption{\textbf{Phase~I simulation pretraining improves real-PIV rollout at "
    r"every stage of Phase~II training.} Paired ablation: both arms start from "
    r"Walrus-1.3B and are trained on real PIV with identical settings "
    r"($\mathrm{lr}=5{\times}10^{-5}$, batch~1, 200 steps/epoch); they differ only in "
    r"whether the cylinder-simulation Phase~I stage was run first. Epoch~0 is the "
    r"zero-shot rollout of each starting checkpoint. Metrics are 64-step "
    r"rollout means on the held-out PIV split. Bold marks the better arm.}",
    r"\label{tab:appendix_pretrain_benefit}",
    r"\small",
    r"\setlength{\tabcolsep}{4.5pt}",
    r"\begin{tabular}{rrrcrrcrr}",
    r"\toprule",
    r" & \multicolumn{3}{c}{VRMSE $\downarrow$} & \multicolumn{3}{c}{NRMSE $\downarrow$}"
    r" & \multicolumn{2}{c}{Pearson $r$ $\uparrow$} \\",
    r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-9}",
    r"PIV epochs & \makecell{no\\Phase~I} & \makecell{+\,Phase~I} & gain"
    r" & \makecell{no\\Phase~I} & \makecell{+\,Phase~I} & gain"
    r" & \makecell{no\\Phase~I} & \makecell{+\,Phase~I} \\",
    r"\midrule",
]
for ep, vB, vA, vr, nB, nA, nr, rB, rA in rows:
    tag = str(ep)
    lines.append(
        f"  {tag} & {fmt(vB, False)} & {fmt(vA, True)} & {vr:.2f}$\\times$"
        f" & {fmt(nB, False)} & {fmt(nA, True)} & {nr:.2f}$\\times$"
        f" & {rB:.3f} & \\textbf{{{rA:.3f}}} \\\\")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

# ---- second table: where the benefit lives, by rollout horizon ----
lines += [
    r"\begin{table}[t]",
    r"\centering",
    r"\caption{\textbf{The benefit of Phase~I is concentrated at long rollout "
    r"horizons.} Rollout VRMSE ($\downarrow$) on real PIV, decomposed into the "
    r"time windows logged during validation, for the same paired arms as "
    r"Table~\ref{tab:appendix_pretrain_benefit}. Once Phase~II training has run, "
    r"the two arms are indistinguishable over the first few steps; the gap that "
    r"remains is almost entirely in the $T{=}8{:}22$ and $T{=}22{:}64$ windows, "
    r"indicating that Phase~I buys long-horizon stability rather than one-step "
    r"accuracy. Epoch~0 is the zero-shot rollout of each starting checkpoint.}",
    r"\label{tab:appendix_pretrain_benefit_horizon}",
    r"\small",
    r"\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{rl" + "r" * len(WINDOWS) + r"}",
    r"\toprule",
    r"PIV epochs & Arm & " + " & ".join(f"$T{{=}}{w[2:].replace(':','{:}')}$"
                                        for w in WINDOWS) + r" \\",
    r"\midrule",
]
for i, ep in enumerate(EPOCHS):
    a, b = data[ep]["A"], data[ep]["B"]
    tag = str(ep)
    vb = [val(b, f"full_VRMSE_{w}_mean") for w in WINDOWS]
    va = [val(a, f"full_VRMSE_{w}_mean") for w in WINDOWS]
    lines.append(f"  \\multirow{{2}}{{*}}{{{tag}}} & no Phase~I & "
                 + " & ".join(f"{x:.3f}" for x in vb) + r" \\")
    lines.append("   & +\\,Phase~I & "
                 + " & ".join(
                     f"\\textbf{{{x:.3f}}}" if round(x, 3) < round(y, 3)
                     else f"{x:.3f}"
                     for x, y in zip(va, vb)) + r" \\")
    if i < len(EPOCHS) - 1:
        lines.append(r"\addlinespace[2pt]")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

path = f"{OUT}/tab_appendix_pretrain_benefit.tex"
with open(path, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {path}")
print(f"\narms:\n  +Phase I : {os.path.basename(A_RUN)}\n  no Phase I: {os.path.basename(B_RUN)}")
print("\nsummary (VRMSE T=all):")
for ep, vB, vA, vr, *_ in rows:
    print(f"  ep{ep:>3}: no-P1 {vB:.4f}  +P1 {vA:.4f}  gain {vr:.2f}x")
