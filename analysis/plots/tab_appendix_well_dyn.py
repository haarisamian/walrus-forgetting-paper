"""
Appendix detail table: absolute per-field error at every Phase-1 checkpoint,
under BOTH normalisations.

NRMSE divides by RMS(y), VRMSE by sigma(y). They coincide for zero-mean fields
and diverge in proportion to |mu|/sigma, so reporting both shows which
conclusions depend on a channel's uniform background.

SOURCE: forget_eval_results/{pretrained,phase1_dyn_step5,10,15,20},
        valid_loss_dict -> <field>_{METRIC}_T=all_mean, averaged over fields.
No channels excluded.
"""
import sys as _s, pathlib as _p; _s.path.insert(0, str(_p.Path(__file__).resolve().parents[1]))
from analysis._paths import ROOT
import glob, io, pickle, re
import numpy as np, torch
torch.storage._load_from_bytes = lambda b: torch.load(io.BytesIO(b), map_location="cpu",
                                                      weights_only=False)
FE = f"{ROOT}/walrus/experiments/forget_eval_results"
CKPTS = [("pretrained","pretrained"),("step 5","phase1_dyn_step5"),
         ("step 10","phase1_dyn_step10"),("step 15","phase1_dyn_step15"),
         ("step 20","phase1_dyn_step20")]
DATASETS = [
 ("acoustic_scattering_discontinuous", r"acoustic\_scattering\_disc."),
 ("acoustic_scattering_inclusions",    r"acoustic\_scattering\_incl."),
 ("acoustic_scattering_maze",          r"acoustic\_scattering\_maze"),
 ("active_matter",                     r"active\_matter"),
 ("helmholtz_staircase",               r"helmholtz\_staircase"),
 ("MHD_64",                            r"MHD\_64"),
 ("planetswe",                         r"planetswe"),
 ("shear_flow",                        r"shear\_flow"),
 ("trl2d",                             r"turbulent\_radiative\_layer\_2D"),
 ("turbcool",                          r"turbulence\_gravity\_cooling"),
]

def mean_metric(ckpt, ds, metric):
    fs = glob.glob(f"{FE}/{ckpt}/{ds}/**/valid_loss_dict_*.pkl", recursive=True)
    assert fs, f"missing {ckpt}/{ds}"
    D = pickle.load(open(fs[0], "rb")); vals = []
    for k, v in D.items():
        m = re.match(rf".*/(.+)_{metric}_T=all_mean$", k)
        if m and m.group(1) != "full":
            vals.append(float(v.item() if hasattr(v, "item") else v))
    assert vals, f"no {metric} fields in {ckpt}/{ds}"
    return float(np.mean(vals))

rows = []
for ds, disp in DATASETS:
    n = [mean_metric(c, ds, "NRMSE") for _, c in CKPTS]
    v = [mean_metric(c, ds, "VRMSE") for _, c in CKPTS]
    rows.append((disp, n, v))

def fmt(vals):
    lo = min(range(len(vals)), key=lambda i: vals[i])
    return [(rf"\textbf{{{x:.4f}}}" if i == lo else f"{x:.4f}")
            for i, x in enumerate(vals)]

L = [r"% Generated by tab_appendix_well_dyn.py -- do not edit by hand.",
 r"% Source: forget_eval_results/{pretrained,phase1_dyn_step5,10,15,20}",
 r"% Preamble: \usepackage{booktabs}   (table* spans both columns)",
 r"\begin{table*}[t]", r"\centering",
 r"\setlength{\belowcaptionskip}{6pt}",
 r"\caption{Well benchmark mean per-field error at each Phase~I"
 r" forgetting-dynamics checkpoint, under both normalisations. Metric: mean of"
 r" per-field \texttt{\{N,V\}RMSE\_T=all\_mean} from the one-step validation"
 r" pass. NRMSE divides by $\mathrm{RMS}(y)$, VRMSE by $\sigma(y)$; the two"
 r" coincide for zero-mean fields and diverge in proportion to a channel's"
 r" uniform background, so VRMSE is the comparable metric across physically"
 r" different channels and $\mathrm{VRMSE}=1$ means no better than predicting"
 r" the spatial mean. Bold = lowest (best) per row. \emph{Pretrained}:"
 r" Walrus-1.3B before any cylinder finetuning. \emph{Step $k$}: after $k$"
 r" epochs of Phase~I cylinder finetuning (200 gradient steps/epoch).}",
 r"\label{tab:appendix_well_dyn}", r"\footnotesize",
 r"\setlength{\tabcolsep}{4pt}",
 r"\begin{tabular}{l" + "r"*5 + "r"*5 + r"}", r"\toprule",
 r" & \multicolumn{5}{c}{NRMSE} & \multicolumn{5}{c}{VRMSE} \\",
 r"\cmidrule(lr){2-6} \cmidrule(lr){7-11}",
 r"\textbf{Dataset} & " + " & ".join(rf"\textbf{{{c}}}" for c,_ in CKPTS)
   + " & " + " & ".join(rf"\textbf{{{c}}}" for c,_ in CKPTS) + r" \\",
 r"\midrule"]
for disp, n, v in rows:
    L.append(f"  {disp} & " + " & ".join(fmt(n)) + " & " + " & ".join(fmt(v)) + r" \\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
out = f"{ROOT}/realpdebench/analysis/plots/tab_appendix_well_dyn.tex"
open(out, "w").write("\n".join(L))
print(f"wrote {out}\n")
print(f"{'dataset':32}" + "".join(f"{c:>9}" for c,_ in CKPTS) + "  |" +
      "".join(f"{c:>9}" for c,_ in CKPTS))
print(f"{'':32}{'--- NRMSE ---':^45}  |{'--- VRMSE ---':^45}")
for disp, n, v in rows:
    nm = re.sub(r"\\","",disp)
    print(f"{nm:32}" + "".join(f"{x:9.4f}" for x in n) + "  |" +
          "".join(f"{x:9.4f}" for x in v))
