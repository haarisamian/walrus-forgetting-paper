"""
Phase-1 forgetting table.

SOURCE: experiments/forget_eval_results/{pretrained,phase1_dyn_step5,phase1_dyn_step20},
valid_loss_dict -> <field>_NRMSE_T=all_mean, averaged over fields.
NOT the dump_well_* dirs: those are a separate visualisation eval whose numbers
differ (helmholtz 0.0353 vs 0.0374).

NO channels are excluded. active_matter's `concentration` has a genuinely tiny
NRMSE (2.7e-5 one-step) because the field is dominated by a large uniform mean,
so NRMSE's denominator is huge -- not because the model fails on it. Its ratio
(5.96) is perfectly well defined, and dropping it only changes the field count.

EMBEDDING NOTE: walrus ties fields by NAME (tie_fields=True, multidataset.py:153),
so field_to_index_map keys on the bare string. Phase 1 trains on cylinder_numerical,
whose fields are exactly velocity_x, velocity_y. PlanetSWE stores velocity_phi /
velocity_theta -- different strings, therefore DIFFERENT field indices and
different embeddings. Its velocity is physically velocity but did not share the
fine-tuned embedding, so it is flagged in the table.
"""
import sys as _s, pathlib as _p; _s.path.insert(0, str(_p.Path(__file__).resolve().parents[1]))
from analysis._paths import ROOT
import glob, io, pickle
import numpy as np, torch
torch.storage._load_from_bytes = lambda b: torch.load(io.BytesIO(b), map_location="cpu",
                                                      weights_only=False)
EVAL = f"{ROOT}/walrus/experiments/forget_eval_results"
CYL_FIELDS = {"velocity_x", "velocity_y"}          # what Phase 1 actually trained on

#  label, dir, [(field, is_velocity), ...]
DATASETS = [
 ("Active Matter","active_matter",[("D_xx",0),("D_xy",0),("D_yx",0),("D_yy",0),
    ("E_xx",0),("E_xy",0),("E_yx",0),("E_yy",0),("concentration",0),
    ("velocity_x",1),("velocity_y",1)]),
 ("TRL-2D","trl2d",[("density",0),("pressure",0),("velocity_x",1),("velocity_y",1)]),
 ("Turbcool","turbcool",[("density",0),("pressure",0),("temperature",0),
    ("velocity_x",1),("velocity_y",1),("velocity_z",1)]),
 ("Shear Flow","shear_flow",[("tracer",0),("pressure",0),("velocity_x",1),("velocity_y",1)]),
 ("MHD-64","MHD_64",[("density",0),("magnetic_field_x",0),("magnetic_field_y",0),
    ("magnetic_field_z",0),("velocity_x",1),("velocity_y",1),("velocity_z",1)]),
 ("Helmholtz Staircase","helmholtz_staircase",[("pressure_im",0),("pressure_re",0)]),
 ("Acoustic (disc.)","acoustic_scattering_discontinuous",
    [("pressure",0),("velocity_x",1),("velocity_y",1)]),
 ("Acoustic (incl.)","acoustic_scattering_inclusions",
    [("pressure",0),("velocity_x",1),("velocity_y",1)]),
 ("Acoustic (maze)","acoustic_scattering_maze",
    [("pressure",0),("velocity_x",1),("velocity_y",1)]),
 ("Planet SWE","planetswe",[("height",0),("velocity_phi",1),("velocity_theta",1)]),
]
GROUPS = [("Fluid dynamics",["Active Matter","TRL-2D","Turbcool","Shear Flow"]),
          ("Magnetohydrodynamics",["MHD-64"]),
          ("Wave / acoustics",["Helmholtz Staircase","Acoustic (disc.)",
                               "Acoustic (incl.)","Acoustic (maze)"]),
          ("Geophysics",["Planet SWE"])]

def load(ckpt, ds):
    fs = glob.glob(f"{EVAL}/{ckpt}/{ds}/**/valid_loss_dict_*.pkl", recursive=True)
    assert fs, f"missing {ckpt}/{ds}"
    return pickle.load(open(fs[0], "rb"))

def get(d, f, metric="NRMSE"):
    t = f"{f}_{metric}_T=all_mean"
    for k, v in d.items():
        if k.endswith(t) and f"full_{metric}" not in k:
            return float(v.item() if hasattr(v, "item") else v)
    raise KeyError(f"{f}/{metric}")

info = {}
for lab, ds, chans in DATASETS:
    a, b5, b20 = (load(c, ds) for c in ("pretrained","phase1_dyn_step5","phase1_dyn_step20"))
    F  = [f for f, _ in chans]
    vk = [f for f, v in chans if v]
    nk = [f for f, v in chans if not v]
    rec = dict(nv=len(vk), nn=len(nk), shares=bool(set(vk) & CYL_FIELDS))
    for M in ("NRMSE", "VRMSE"):
        mn = lambda D, ks, M=M: float(np.mean([get(D, k, M) for k in ks])) if ks else None
        rec[f"pre_{M}"] = mn(a, F)
        rec[f"r5_{M}"]  = mn(b5, F) / mn(a, F)
        rec[f"r20_{M}"] = mn(b20, F) / mn(a, F)
        rec[f"v20_{M}"] = (mn(b20, vk) / mn(a, vk)) if vk else None
        rec[f"n20_{M}"] = (mn(b20, nk) / mn(a, nk)) if nk else None
    info[lab] = rec

